namespace Ampache\Module\Api\Method;

use Ampache\MockeryTestCase;
use Ampache\Module\Api\Authentication\GatekeeperInterface;
use Ampache\Module\Api\Method\Exception\RequestParamMissingException;
use Ampache\Module\Api\Output\ApiOutputInterface;
use Ampache\Repository\BookmarkRepositoryInterface;
use Ampache\Repository\Model\Bookmark;
use Ampache\Repository\Model\User;
use Mockery\MockInterface;
use Override;
use PHPUnit\Framework\Attributes\DataProvider;
use Psr\Http\Message\ResponseInterface;
use Psr\Http\Message\StreamInterface;

class BookmarkMethodTest extends MockeryTestCase
{
    private BookmarkRepositoryInterface|MockInterface|null $bookmarkRepository;
    private ?BookmarkMethod $subject;

    /**
     * The same method serves both api versions; the version is only handed to the output
     *
     * @return array<string, array{0: int}>
     */
    public static function apiVersionProvider(): array
    {
        return [
            'api6' => [6],
            'api8' => [8],
        ];
    }

    #[DataProvider(methodName: 'apiVersionProvider')]
    public function testHandleReturnsEmptyIfNotFound(int $apiVersion): void
    {
        $gatekeeper = $this->mock(GatekeeperInterface::class);
        $response   = $this->mock(ResponseInterface::class);
        $output     = $this->mock(ApiOutputInterface::class);
        $user       = $this->mock(User::class);
        $stream     = $this->mock(StreamInterface::class);

        $result = 'empty-result';

        $this->bookmarkRepository->shouldReceive('findById')
            ->with(666)
            ->once()
            ->andReturnNull();

        $output->shouldReceive('writeEmpty')
            ->with($apiVersion, null)
            ->once()
            ->andReturn($result);

        $response->shouldReceive('getBody')
            ->withNoArgs()
            ->once()
            ->andReturn($stream);
        $stream->shouldReceive('write')
            ->with($result)
            ->once();

        $this->assertSame(
            $response,
            $this->subject->handle(
                $gatekeeper,
                $response,
                $output,
                ['filter' => '666', 'api_format' => 'json', 'auth' => 'some-auth'],
                $user,
                $apiVersion
            )
        );
    }

    /**
     * A bookmark belonging to somebody else must not leak
     */
    #[DataProvider(methodName: 'apiVersionProvider')]
    public function testHandleReturnsEmptyIfNotOwnedByUser(int $apiVersion): void
    {
        $gatekeeper = $this->mock(GatekeeperInterface::class);
        $response   = $this->mock(ResponseInterface::class);
        $output     = $this->mock(ApiOutputInterface::class);
        $user       = $this->mock(User::class);
        $stream     = $this->mock(StreamInterface::class);
        $bookmark   = $this->mock(Bookmark::class);

        $result = 'empty-result';

        $this->bookmarkRepository->shouldReceive('findById')
            ->with(666)
            ->once()
            ->andReturn($bookmark);

        $bookmark->shouldReceive('ownedByUser')
            ->with($user)
            ->once()
            ->andReturnFalse();

        $output->shouldReceive('writeEmpty')
            ->with($apiVersion, null)
            ->once()
            ->andReturn($result);

        $response->shouldReceive('getBody')
            ->withNoArgs()
            ->once()
            ->andReturn($stream);
        $stream->shouldReceive('write')
            ->with($result)
            ->once();

        $this->assertSame(
            $response,
            $this->subject->handle(
                $gatekeeper,
                $response,
                $output,
                ['filter' => '666', 'api_format' => 'json', 'auth' => 'some-auth'],
                $user,
                $apiVersion
            )
        );
    }

    #[DataProvider(methodName: 'apiVersionProvider')]
    public function testHandleReturnsResult(int $apiVersion): void
    {
        $gatekeeper = $this->mock(GatekeeperInterface::class);
        $response   = $this->mock(ResponseInterface::class);
        $output     = $this->mock(ApiOutputInterface::class);
        $user       = $this->mock(User::class);
        $stream     = $this->mock(StreamInterface::class);
        $bookmark   = $this->mock(Bookmark::class);

        $bookmarkId = 42;
        $result     = 'some-result';

        $this->bookmarkRepository->shouldReceive('findById')
            ->with(666)
            ->once()
            ->andReturn($bookmark);

        $bookmark->shouldReceive('ownedByUser')
            ->with($user)
            ->once()
            ->andReturnTrue();
        $bookmark->shouldReceive('getId')
            ->withNoArgs()
            ->once()
            ->andReturn($bookmarkId);

        // the resolved api version must reach the output untouched
        $output->shouldReceive('bookmarks')
            ->with($apiVersion, [$bookmarkId], 'some-auth', true, false)
            ->once()
            ->andReturn($result);

        $response->shouldReceive('getBody')
            ->withNoArgs()
            ->once()
            ->andReturn($stream);
        $stream->shouldReceive('write')
            ->with($result)
            ->once();

        $this->assertSame(
            $response,
            $this->subject->handle(
                $gatekeeper,
                $response,
                $output,
                [
                    'filter' => '666',
                    'include' => 1,
                    'api_format' => 'json',
                    'auth' => 'some-auth',
                ],
                $user,
                $apiVersion
            )
        );
    }

    #[DataProvider(methodName: 'apiVersionProvider')]
    public function testHandleThrowsIfFilterIsMissing(int $apiVersion): void
    {
        $gatekeeper = $this->mock(GatekeeperInterface::class);
        $response   = $this->mock(ResponseInterface::class);
        $output     = $this->mock(ApiOutputInterface::class);
        $user       = $this->mock(User::class);

        $this->expectException(RequestParamMissingException::class);
        $this->expectExceptionMessage(sprintf(T_('Bad Request: %s'), 'filter'));

        $this->subject->handle(
            $gatekeeper,
            $response,
            $output,
            ['api_format' => 'json', 'auth' => 'some-auth'],
            $user,
            $apiVersion
        );
    }

    #[Override]
    protected function setUp(): void
    {
        $this->bookmarkRepository = $this->mock(BookmarkRepositoryInterface::class);

        $this->subject = new BookmarkMethod(
            $this->bookmarkRepository
        );
    }
}
